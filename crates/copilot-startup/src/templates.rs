//! The built-in notification templates `seed_builtin_templates` inserts
//! (`app/notifications/services/template_seeds.py`'s `BUILTIN_TEMPLATES`),
//! pinned to Python's list by `startup_vectors.json`.

/// One built-in template: a `notification_template` row with
/// `is_default = 1`, no customer and `created_by = 'system'`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BuiltinTemplate {
    /// `name`: the seeding key (an existing built-in of that name is never
    /// rewritten).
    pub name: &'static str,
    /// `description`.
    pub description: &'static str,
    /// `trigger` (`None`: usable with any trigger).
    pub trigger: Option<&'static str>,
    /// `format`.
    pub format: &'static str,
    /// `subject_template`.
    pub subject_template: Option<&'static str>,
    /// `body_template`.
    pub body_template: &'static str,
}

