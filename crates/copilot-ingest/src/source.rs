//! One indexer document as the ingest reads it — `GenericSourceModel` and
//! `GenericAlertModel` of `app/incidents/schema/incident_alert.py`, and
//! `get_single_alert_details` (`POST /incidents/alerts/alert/details`, and
//! the first step of every alert creation).

use copilot_auth::pyvalue::{PyValue, float_repr};
use copilot_upstream::model::{
    Field, Invalid, Model, Ty, field, format_validation_error, validate,
};
use copilot_wazuh::error::PyErr;

use crate::IngestState;
use crate::es;
use crate::py::type_name;

/// `_stringify_numeric_values`: a number where a string field is declared
/// becomes its `str()` (a bool stays a bool).
fn stringify(v: &PyValue) -> PyValue {
    match v {
        PyValue::Int(i) => PyValue::Str(i.clone()),
        PyValue::Float(f) => PyValue::Str(float_repr(*f)),
        other => other.clone(),
    }
}

const OPT_STR: Ty = Ty::Nullable(&Ty::Str);

fn no_rule_description() -> PyValue {
    PyValue::Str("No autogenerated rule_description found".into())
}

fn no_syslog_level() -> PyValue {
    PyValue::Str("No autogenerated syslog_level found".into())
}

fn timestamp_default() -> PyValue {
    PyValue::Str("timestamp".into())
}

/// `GenericSourceModel` (`extra="allow"`).
pub static GENERIC_SOURCE: Model = Model::allowing_extra(
    "GenericSourceModel",
    &[
        Field::req("timestamp", Ty::Str).before(stringify),
        Field::opt("timestamp_utc", OPT_STR).before(stringify),
        Field::def("rule_description", OPT_STR, no_rule_description).before(stringify),
        Field::def("syslog_level", OPT_STR, no_syslog_level).before(stringify),
        Field::opt("syslog_type", OPT_STR).before(stringify),
        Field::opt("process_id", OPT_STR).before(stringify),
        Field::opt("agent_name", OPT_STR).before(stringify),
    ],
);

/// `GenericAlertModel` (built from keyword arguments under the aliases).
static GENERIC_ALERT: Model = Model::allowing_extra(
    "GenericAlertModel",
    &[
        Field::req("index", Ty::Str).alias("_index"),
        Field::req("id", Ty::Str).alias("_id"),
        Field::req("version", Ty::Int).alias("_version"),
        Field::req("source", Ty::Any).alias("_source"),
        Field::opt("asset_type_id", Ty::Nullable(&Ty::Int)),
        Field::opt("ioc_value", OPT_STR),
        Field::opt("ioc_type", OPT_STR),
        Field::def("time_field", OPT_STR, timestamp_default),
        Field::opt("syslog_type", OPT_STR),
    ],
);

/// A validated document.
#[derive(Debug, Clone, PartialEq)]
pub struct AlertDetails {
    /// `_index`.
    pub index: String,
    /// `_id`.
    pub id: String,
    /// `syslog_type` (or `integration`).
    pub syslog_type: String,
    /// `GenericSourceModel` as a dict (`dict(model)`: every field, extras
    /// after the declared ones).
    pub source: Vec<(String, PyValue)>,
    /// The `GenericAlertModel` dump by alias (the `/alert/details` body).
    pub dump: PyValue,
}

impl AlertDetails {
    /// `source.to_dict()` (`model_dump(exclude_none=True)`).
    pub fn source_dict(&self) -> Vec<(String, PyValue)> {
        self.source
            .iter()
            .filter(|(_, v)| *v != PyValue::None)
            .cloned()
            .collect()
    }

    /// `alert_details.source.<field>` of a declared `Optional[str]` field.
    pub fn source_str(&self, name: &str) -> Option<&str> {
        crate::py::dict_get(&self.source, name).and_then(PyValue::as_str)
    }
}

/// `x[key]` of an indexer answer, with Python's exception text.
pub fn getitem<'a>(v: &'a PyValue, key: &str) -> Result<&'a PyValue, String> {
    match v {
        PyValue::Dict(d) => {
            crate::py::dict_get(d, key).ok_or_else(|| copilot_auth::pyvalue::str_repr(key))
        }
        PyValue::Str(_) => Err("string indices must be integers, not 'str'".into()),
        PyValue::List(_) => Err("list indices must be integers or slices, not str".into()),
        other => Err(format!(
            "'{}' object is not subscriptable",
            type_name(other)
        )),
    }
}

/// `GenericSourceModel(**source)` and `GenericAlertModel(...)` over one
/// `es.get` answer; `Err` is `str(e)` of what Python raises.
pub fn read_details(alert: &PyValue) -> Result<AlertDetails, String> {
    let raw_source = getitem(alert, "_source")?;
    if !matches!(raw_source, PyValue::Dict(_)) {
        return Err(format!(
            "app.incidents.schema.incident_alert.GenericSourceModel() argument after ** must be a \
             mapping, not {}",
            type_name(raw_source)
        ));
    }
    let source = match validate(&GENERIC_SOURCE, raw_source) {
        Ok(PyValue::Dict(d)) => d,
        Ok(_) => Vec::new(),
        Err(Invalid::Errors(e)) => return Err(format_validation_error(GENERIC_SOURCE.name, &e)),
        Err(Invalid::Abort(_, d)) => return Err(d),
    };
    let declared = |name: &str| crate::py::dict_get(&source, name).cloned();
    let mut syslog_type = declared("syslog_type").unwrap_or(PyValue::None);
    if syslog_type == PyValue::None {
        // `getattr(source_model, "integration", None)`: an extra, any type.
        syslog_type = declared("integration").unwrap_or(PyValue::None);
    }
    if syslog_type == PyValue::None {
        return Err("400: Neither syslog_type nor integration field found in source_model".into());
    }
    // The keyword arguments, evaluated in their order.
    let id = getitem(alert, "_id")?.clone();
    let index = getitem(alert, "_index")?.clone();
    let version = getitem(alert, "_version")?.clone();
    let kwargs = PyValue::Dict(vec![
        ("_source".into(), PyValue::Dict(source.clone())),
        ("_id".into(), id),
        ("_index".into(), index),
        ("_version".into(), version),
        ("syslog_type".into(), syslog_type),
    ]);
    let dump = match validate(&GENERIC_ALERT, &kwargs) {
        Ok(d) => d,
        Err(Invalid::Errors(e)) => return Err(format_validation_error(GENERIC_ALERT.name, &e)),
        Err(Invalid::Abort(_, d)) => return Err(d),
    };
    let text = |k: &str| field(&dump, k).as_str().unwrap_or_default().to_string();
    Ok(AlertDetails {
        index: text("_index"),
        id: text("_id"),
        syslog_type: text("syslog_type"),
        source,
        dump,
    })
}

/// `get_single_alert_details(CreateAlertRequest(index_name, alert_id))`:
/// any failure after the client is built is a 400 `Failed to collect alert
/// details: …`.
pub async fn single_alert_details(
    st: &IngestState,
    index_name: &str,
    alert_id: &str,
) -> Result<AlertDetails, PyErr> {
    tracing::info!(
        target: "copilot::ingest",
        "Fetching alert details for alert {alert_id} in index {index_name}"
    );
    let client = es::async_client(st).await?;
    let result = match es::get(&client, index_name, alert_id).await {
        Ok(doc) => read_details(&doc),
        Err(e) => Err(e.to_string()),
    };
    result.map_err(|e| PyErr::http(400, format!("Failed to collect alert details: {e}")))
}
