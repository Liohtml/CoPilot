"""Generate crates/copilot-markdown/src/tables.rs from the Python runtime.

The Rust port of markdown-it-py needs three facts the Python standard library
supplies at runtime: the HTML5 entity names (``html.entities.html5``, as
``markdown_it.common.entities`` reads them), the code points ``isPunctChar``
accepts (``unicodedata`` categories P* and S*) and the characters
``str.isspace()`` accepts (``str.strip()``, ``re`` ``\\s``). Regenerate after a
Python or markdown-it-py upgrade:

    /var/lib/copilot-venv/bin/python scripts/gen-markdown-tables.py
"""

from __future__ import annotations

import pathlib
import sys
import unicodedata

from markdown_it.common.entities import entities

OUT = pathlib.Path(__file__).resolve().parent.parent / "crates" / "copilot-markdown" / "src" / "tables.rs"


def ranges(pred):
    out = []
    start = None
    for cp in range(sys.maxunicode + 1):
        ok = pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, sys.maxunicode))
    return out


def rust_str(s: str) -> str:
    return '"' + "".join(f"\\u{{{ord(c):x}}}" if not (0x20 <= ord(c) < 0x7F and c not in '"\\') else c for c in s) + '"'


def main() -> None:
    punct = ranges(lambda cp: unicodedata.category(chr(cp)).startswith(("P", "S")))
    space = [cp for cp in range(sys.maxunicode + 1) if chr(cp).isspace()]
    names = sorted(entities)
    lines = [
        "//! Generated by `scripts/gen-markdown-tables.py` from Python "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}); do not edit.",
        "",
        '/// `unicodedata.category(ch).startswith(("P", "S"))`, as inclusive ranges.',
        "pub(crate) const PUNCT_RANGES: &[(u32, u32)] = &[",
    ]
    lines += [f"    (0x{a:x}, 0x{b:x})," for a, b in punct]
    lines += ["];", "", "/// `str.isspace()`.", "pub(crate) const PY_SPACE: &[u32] = &["]
    lines += [f"    0x{cp:x}," for cp in space]
    lines += [
        "];",
        "",
        "/// HTML5 entity names (without `;`) and their characters, sorted by name.",
        "pub(crate) const ENTITIES: &[(&str, &str)] = &[",
    ]
    lines += [f"    ({rust_str(n)}, {rust_str(entities[n])})," for n in names]
    lines += ["];", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(punct)} punct ranges, {len(space)} spaces, {len(names)} entities)")


if __name__ == "__main__":
    main()
