#!/usr/bin/env bash
# Regenerate crates/copilot/tests/fixtures/schema.sql, the schema the Rust e2e
# tests (and CI) load, from a database at this build's last migration.
#
# The schema is the binary's (crates/copilot-migrate): the baseline is the
# Alembic head d15ab1ed7e1e, frozen (scripts/check-alembic-head.py fails on a
# new Python migration), and later changes are Rust migrations. While the
# baseline is the only migration the fixture IS the baseline (a unit test in
# copilot-migrate compares them): dump a database `alembic upgrade head` or
# `copilot migrate` created — the runner's history table is left out unless
# WITH_HISTORY=1. Once a Rust migration follows, dump a database `copilot
# migrate` brought to it with WITH_HISTORY=1, so that the runner finds the
# e2e database recorded (the e2e suite e2e_startup compares the runner's
# result with this file).
#
#   MYSQL_HOST=127.0.0.1 MYSQL_PORT=13306 MYSQL_USER=root scripts/dump-schema.sh
set -euo pipefail
cd "$(dirname "$0")/.."
: "${MYSQL_HOST:=127.0.0.1}" "${MYSQL_PORT:=13306}" "${MYSQL_USER:=root}" "${MYSQL_DATABASE:=copilot}"
OUT=crates/copilot/tests/fixtures/schema.sql
ARGS=(-h"$MYSQL_HOST" -P"$MYSQL_PORT" -u"$MYSQL_USER" ${MYSQL_PWD:+-p"$MYSQL_PWD"} --skip-comments --skip-dump-date)
HISTORY=copilot_rs_schema_history
if [ "${WITH_HISTORY:-0}" = 1 ]; then SKIP=(); DATA=(alembic_version role "$HISTORY"); else SKIP=(--ignore-table="$MYSQL_DATABASE.$HISTORY"); DATA=(alembic_version role); fi
{
  echo "-- CoPilot schema at the Alembic head, for the Rust e2e tests."
  echo "-- Generated by scripts/dump-schema.sh — do not edit by hand."
  echo "SET FOREIGN_KEY_CHECKS=0;"
  mysqldump "${ARGS[@]}" --no-data --skip-add-drop-table "${SKIP[@]}" "$MYSQL_DATABASE" | sed 's/ AUTO_INCREMENT=[0-9]*//'
  mysqldump "${ARGS[@]}" --no-create-info --skip-extended-insert "$MYSQL_DATABASE" "${DATA[@]}"
  echo "SET FOREIGN_KEY_CHECKS=1;"
} > "$OUT"
echo "wrote $OUT ($(grep -c '^CREATE TABLE' "$OUT") tables, head $(grep -o "INSERT INTO \`alembic_version\` VALUES ('[0-9a-f]*')" "$OUT" | grep -o "'.*'"))"
