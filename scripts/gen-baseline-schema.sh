#!/usr/bin/env bash
# Generate the Rust migrations' baseline, crates/copilot-migrate/migrations/0001_baseline.sql:
# the schema `alembic upgrade head` creates on an EMPTY database, dumped the way
# scripts/dump-schema.sh dumps the e2e fixture (crates/copilot/tests/fixtures/schema.sql).
#
# Alembic is frozen at d15ab1ed7e1e (the baseline's revision): this script exists to show
# where the file came from and to regenerate it identically, never to change it — its
# SHA-256 is recorded in `copilot_rs_schema_history` of every database it created, and the
# runner refuses a database whose recorded checksum differs. A unit test in copilot-migrate
# checks the body equals the e2e fixture's.
#
#   MYSQL_HOST=127.0.0.1 MYSQL_PORT=13307 MYSQL_USER=copilot MYSQL_PWD=copilot \
#     PYTHON=/var/lib/copilot-venv/bin/python scripts/gen-baseline-schema.sh
#
# MYSQL_USER must be able to create and drop a database. The throwaway database
# (BASELINE_DATABASE, default copilot_baseline_gen) is dropped again at the end.
set -euo pipefail
cd "$(dirname "$0")/.."
: "${MYSQL_HOST:=127.0.0.1}" "${MYSQL_PORT:=13306}" "${MYSQL_USER:=root}" "${PYTHON:=backend/.venv/bin/python}"
DB="${BASELINE_DATABASE:-copilot_baseline_gen}"
OUT=crates/copilot-migrate/migrations/0001_baseline.sql
CONN=(-h"$MYSQL_HOST" -P"$MYSQL_PORT" -u"$MYSQL_USER" ${MYSQL_PWD:+-p"$MYSQL_PWD"})
ARGS=("${CONN[@]}" --skip-comments --skip-dump-date)
mysql "${CONN[@]}" -e "DROP DATABASE IF EXISTS \`$DB\`; CREATE DATABASE \`$DB\`"
trap 'mysql "${CONN[@]}" -e "DROP DATABASE IF EXISTS \`$DB\`"' EXIT
# The Python backend hard-codes its database name after MYSQL_URL; a trailing `?` turns that
# suffix into an empty query string, so `host:port/<db>?` names the throwaway database.
(cd backend && MYSQL_URL="${MYSQL_HOST}:${MYSQL_PORT}/${DB}?" MYSQL_USER="$MYSQL_USER" MYSQL_PASSWORD="${MYSQL_PWD:-}" \
  MYSQL_ROOT_PASSWORD="${MYSQL_PWD:-}" JWT_SECRET=baseline-generator-not-a-secret \
  "$PYTHON" -c "from app.db.db_setup import apply_migrations; apply_migrations()" >/dev/null 2>&1)
{
  echo "-- CoPilot schema at Alembic d15ab1ed7e1e: the baseline of the Rust migrations (copilot-migrate)."
  echo "-- Generated by scripts/gen-baseline-schema.sh from an empty database \`alembic upgrade head\` migrated."
  echo "-- Never edit: its SHA-256 is recorded in copilot_rs_schema_history of every database it created."
  echo "SET FOREIGN_KEY_CHECKS=0;"
  mysqldump "${ARGS[@]}" --no-data --skip-add-drop-table "$DB" | sed 's/ AUTO_INCREMENT=[0-9]*//'
  mysqldump "${ARGS[@]}" --no-create-info --skip-extended-insert "$DB" alembic_version role
  echo "SET FOREIGN_KEY_CHECKS=1;"
} > "$OUT"
echo "wrote $OUT ($(grep -c '^CREATE TABLE' "$OUT") tables, head $(grep -o "INSERT INTO \`alembic_version\` VALUES ('[0-9a-f]*')" "$OUT" | grep -o "'.*'"))"
